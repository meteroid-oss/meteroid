CREATE TYPE "TaxIdCollectionEnum" AS ENUM ('OFF', 'OPTIONAL', 'REQUIRED');

-- A public, reusable link to buy a plan. Each visit that starts a purchase creates a
-- customer and a checkout session.
CREATE TABLE purchase_link
(
    id                 UUID PRIMARY KEY,
    tenant_id          UUID      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    plan_id            UUID      NOT NULL REFERENCES plan (id) ON DELETE CASCADE,
    name               TEXT      NOT NULL,
    -- Public, unguessable identifier used in the URL. Regenerating it disables old URLs.
    token              TEXT      NOT NULL,
    allow_coupon_codes BOOLEAN   NOT NULL DEFAULT FALSE,
    -- Offered to licensed software (e.g. self-hosted instances) as a way to subscribe.
    listed             BOOLEAN   NOT NULL DEFAULT FALSE,
    success_url        TEXT,
    cancel_url         TEXT,
    -- When false, only the country of the buyer's billing address is required.
    require_billing_address BOOLEAN NOT NULL DEFAULT TRUE,
    -- Whether companies are asked for a VAT / tax ID; individuals never are.
    tax_id_collection  "TaxIdCollectionEnum" NOT NULL DEFAULT 'OPTIONAL',
    -- The only buyer type accepted; NULL accepts companies and individuals.
    only_buyer_type    "CustomerTypeEnum",
    created_at         TIMESTAMP NOT NULL DEFAULT NOW(),
    updated_at         TIMESTAMP NOT NULL DEFAULT NOW(),
    archived_at        TIMESTAMP
);

CREATE UNIQUE INDEX purchase_link_token_idx ON purchase_link (token);
CREATE INDEX purchase_link_tenant_plan_idx ON purchase_link (tenant_id, plan_id);

-- One purchase started from a link: ties the customer and checkout it created to the link.
CREATE TABLE purchase_link_session
(
    id                          UUID PRIMARY KEY,
    tenant_id                   UUID      NOT NULL REFERENCES tenant (id) ON DELETE CASCADE,
    purchase_link_id            UUID      NOT NULL REFERENCES purchase_link (id) ON DELETE CASCADE,
    customer_id                 UUID      NOT NULL REFERENCES customer (id) ON DELETE CASCADE,
    checkout_session_id         UUID REFERENCES checkout_session (id) ON DELETE SET NULL,
    -- Generated by the purchase page per visit: resubmitting reuses this purchase.
    attempt_id                  TEXT      NOT NULL,
    -- Set when licensed software started the purchase: the license is bound to it.
    license_instance_id         TEXT,
    license_instance_public_key TEXT,
    created_at                  TIMESTAMP NOT NULL DEFAULT NOW(),
    -- Set once the customer was archived because the purchase was abandoned.
    cleaned_up_at               TIMESTAMP
);

CREATE INDEX purchase_link_session_link_idx ON purchase_link_session (purchase_link_id, created_at);
CREATE UNIQUE INDEX purchase_link_session_attempt_idx ON purchase_link_session (purchase_link_id, attempt_id);
CREATE INDEX purchase_link_session_customer_idx ON purchase_link_session (customer_id);
CREATE INDEX purchase_link_session_checkout_idx ON purchase_link_session (checkout_session_id);
CREATE INDEX purchase_link_session_cleanup_idx ON purchase_link_session (created_at) WHERE cleaned_up_at IS NULL;

-- Proof-of-work challenges already used to start a purchase; kept until they expire.
CREATE TABLE purchase_pow_spent
(
    challenge  TEXT PRIMARY KEY,
    expires_at TIMESTAMP NOT NULL
);

CREATE INDEX purchase_pow_spent_expires_idx ON purchase_pow_spent (expires_at);
